from fastapi import APIRouter, Depends, HTTPException
from bson import ObjectId
from app.database import posters_collection, businesses_collection, users_collection
from app.models.poster import PosterDB
from app.schemas.poster import PosterCreate, PosterOut
from app.routers.auth import get_current_user_id
from app.services.groq_service import generate_poster_config

router = APIRouter(prefix="/posters", tags=["posters"])


@router.post("", response_model=PosterOut)
async def create_poster(payload: PosterCreate, user_id: str = Depends(get_current_user_id)):
    # 1. Enforce 2 posters per account limit
    existing_count = await posters_collection.count_documents({"user_id": user_id})
    if existing_count >= 2:
        raise HTTPException(
            status_code=400,
            detail="Poster generation limit reached. You can only generate up to 2 posters on the free tier."
        )

    # 2. Retrieve business details
    biz_doc = await businesses_collection.find_one({"_id": ObjectId(payload.business_id), "user_id": user_id})
    if not biz_doc:
        raise HTTPException(status_code=404, detail="Business profile not found")

    # 3. Retrieve user model settings
    user = await users_collection.find_one({"_id": ObjectId(user_id)})
    user_settings = user.get("settings", {}) if user else {}
    model_override = user_settings.get("model")

    # 4. Generate AI poster design specifications
    poster_config = generate_poster_config(
        business_name=biz_doc["name"],
        business_desc=biz_doc.get("description", ""),
        category=biz_doc["category"],
        goal=payload.goal,
        promo_details=payload.promo_details,
        model=model_override
    )

    # 5. Save the poster config to database
    poster = PosterDB(
        user_id=user_id,
        business_id=payload.business_id,
        template_id=poster_config["template_id"],
        goal=payload.goal,
        content={
            "headline": poster_config["headline"],
            "tagline": poster_config["tagline"],
            "details": poster_config["details"],
            "cta": poster_config["cta"],
            "logo_url": payload.logo_url,
            "image_url": payload.image_url
        },
        aspect_ratio=payload.aspect_ratio,
        logo_url=payload.logo_url,
        image_url=payload.image_url
    )
    result = await posters_collection.insert_one(poster.model_dump())
    
    return PosterOut(
        id=str(result.inserted_id),
        business_id=poster.business_id,
        template_id=poster.template_id,
        goal=poster.goal,
        content=poster.content,
        aspect_ratio=poster.aspect_ratio,
        created_at=poster.created_at
    )


@router.get("", response_model=list[PosterOut])
async def list_posters(user_id: str = Depends(get_current_user_id)):
    """List all posters generated by the current user."""
    cursor = posters_collection.find({"user_id": user_id})
    docs = await cursor.to_list(length=50)
    result = []
    for doc in docs:
        result.append(PosterOut(
            id=str(doc.pop("_id")),
            business_id=doc["business_id"],
            template_id=doc["template_id"],
            goal=doc["goal"],
            content=doc["content"],
            aspect_ratio=doc["aspect_ratio"],
            created_at=doc["created_at"]
        ))
    return result


@router.delete("/{poster_id}")
async def delete_poster(poster_id: str, user_id: str = Depends(get_current_user_id)):
    """Delete a poster by ID, freeing up capacity."""
    result = await posters_collection.delete_one({"_id": ObjectId(poster_id), "user_id": user_id})
    if result.deleted_count == 0:
        raise HTTPException(status_code=404, detail="Poster not found or not owned by you")
    return {"ok": True}
