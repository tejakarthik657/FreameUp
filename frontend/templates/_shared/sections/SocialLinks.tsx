export function SocialLinks({ business, className = "" }: SocialLinksProps) {
  const links: { platform: string; url: string; label: string }[] = [];

  if (business.instagram) {
    links.push({ platform: "instagram", url: business.instagram, label: "Instagram" });
  }
  if (business.facebook) {
    links.push({ platform: "facebook", url: business.facebook, label: "Facebook" });
  }
  if (business.threads) {
    links.push({ platform: "threads", url: business.threads, label: "Threads" });
  }
  if (business.whatsapp) {
    links.push({ platform: "whatsapp", url: `https://wa.me/${business.whatsapp}`, label: "WhatsApp" });
  }
  if (business.email) {
    links.push({ platform: "email", url: `mailto:${business.email}`, label: "Email" });
  }

  if (links.length === 0) return null;

  return (
    <div className={`flex gap-4 ${className}`}>
      {links.map((link) => (
        <a
          key={link.platform}
          href={link.url}
          target="_blank"
          rel="noopener noreferrer"
          className="w-10 h-10 rounded-full border border-white/15 flex items-center justify-center hover:border-[#c9a84c] hover:text-[#c9a84c] transition-colors"
          aria-label={link.label}
        >
          {link.platform === "email" ? (
            <svg className="w-4 h-4" fill="none" stroke="currentColor" viewBox="0 0 24 24">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M3 8l7.89 5.26a2 2 0 002.22 0L21 8M5 19h14a2 2 0 002-2V7a2 2 0 00-2-2H5a2 2 0 00-2 2v10a2 2 0 002 2z" />
            </svg>
          ) : (
            <svg className="w-4 h-4" viewBox="0 0 24 24">
              <path d={platformIcons[link.platform]} fill="currentColor" />
            </svg>
          )}
        </a>
      ))}
    </div>
  );
}
